# =============================================================================
# core.schemas.report — the final artifact + before/after comparison
# =============================================================================
# HOW it fits in the pipeline:
#   experiment data ──report builder──▶ Report (deterministic, stored JSONB)
#                                          │
#                    fix-prompt generator reads Report (no other input)
#                    compare reads two Reports
#
# WHY the Report is built ONLY from stored data (never live objects):
#   The honesty principle requires every number to be traceable to a stored
#   bucket or evidence row. Building the report from the DB (not from in-
#   memory state) means: (a) re-generation is deterministic, (b) a report
#   survives a backend restart, (c) tests can build one from fixtures with no
#   running experiment.
#
# WHY `limitations` and `missing_metrics` are first-class fields:
#   A report that only lists what we found is marketing. A report that also
#   lists what we COULDN'T see is engineering. The frontend renders these in
#   a distinct "Limitations" section — they are not optional polish, they are
#   part of the claim's honesty.
# =============================================================================

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, Field

from core.schemas.experiment import ExperimentCreate, ExperimentState
from core.schemas.metrics import Evidence, PhaseStats, OptionalMetric


class RecommendationPriority(str, Enum):
    P1 = "P1"  # fix before this reaches production
    P2 = "P2"  # fix soon
    P3 = "P3"  # nice to have


class Recommendation(BaseModel):
    """One actionable fix. Deterministic — generated by a rule table in
    core/report/builder.py that maps evidence patterns to recommendations
    (see §14.4 of the spec). No LLM writes these; an LLM may later EXPAND
    the rationale in P2, but the title/priority/evidence_refs stand alone."""

    priority: RecommendationPriority
    title: str            # imperative, specific: "Add cache fallback for /api/cart"
    rationale: str        # why, grounded in the measured evidence
    # Indexes into Report.evidence — lets the UI draw a line from the
    # recommendation to the measurements that justify it. A recommendation
    # with empty evidence_refs should not exist (builder must not emit one).
    evidence_refs: list[int] = Field(default_factory=list)


class Report(BaseModel):
    """The complete experiment report. Stored 1:1 in `reports.report`.

    Field groups:
      - what was asked for: config
      - what happened:      final_state, stop_reason, phases, baseline_vs_fault
      - what we proved:     evidence, affected_services, recovery, capacity
      - what we couldn't:   predicted_not_observed, missing_metrics, limitations
      - what to do:         recommendations, fix_prompt
    """

    experiment_id: UUID
    generated_at: datetime
    # "live" = built from a real run just completed; "recorded" = replayed
    # from a saved fixture (demo fallback). The UI shows a RECORDED badge —
    # never present a replay as live.
    data_source: Literal["live", "recorded"] = "live"
    config: ExperimentCreate
    final_state: ExperimentState
    # Populated when AUTO_STOPPED/ABORTED/FAILED — e.g. "Safety auto-stop:
    # error rate 63% > 50% for 5s". Always human-readable, never an enum name.
    stop_reason: str | None = None

    # --- measurements ---
    phases: list[PhaseStats] = Field(default_factory=list)
    # Per-metric delta fault-minus-baseline (or last-step-minus-first for
    # capacity). Keys like "p95_ms", "error_rate". None when either side is
    # missing — never a fabricated 0 delta.
    baseline_vs_fault: dict[str, float | None] | None = None

    # --- resilience answers (fault experiments) ---
    recovery_time_s: float | None = None
    # None = not a fault experiment; True/False only when recovery was
    # actually measured. "False" means "not recovered within timeout" — the
    # report NEVER says "recovered" without a measurement.
    recovered: bool | None = None

    # --- capacity answers (capacity experiments) ---
    highest_passing_multiplier: float | None = None
    first_breach_multiplier: float | None = None
    tested_multipliers: list[float] = Field(default_factory=list)
    # Breaking-point wording is generated from the two fields above:
    #   both set → "between X and Y"
    #   only highest_passing → "no breach up to X (limit not determined)"
    #   only first_breach → shouldn't happen (step 1 always tests something)

    # --- bottleneck (P2) ---
    bottleneck: Literal[
        "cpu_bound",
        "memory_pressure",
        "db_connection_exhaustion",
        "downstream_latency",
        "load_generator_limited",
        "unknown",
    ] = "unknown"  # default is unknown — the honest default when data is missing
    bottleneck_evidence: list[str] = Field(default_factory=list)
    # Which signals were available vs missing — rendered next to the
    # classification so the user can judge its confidence.
    bottleneck_signals_available: list[str] = Field(default_factory=list)
    bottleneck_signals_missing: list[str] = Field(default_factory=list)

    # --- impact ---
    # Services with ≥1 Evidence row — the only "verified impact" list.
    affected_services: list[str] = Field(default_factory=list)
    # On the predicted blast-radius path but with NO evidence. Distinguished
    # from affected_services so the report can say "worker was predicted to
    # suffer but showed no measurable impact (no worker metrics available)".
    predicted_not_observed: list[str] = Field(default_factory=list)
    evidence: list[Evidence] = Field(default_factory=list)

    # --- honesty ---
    limitations: list[str] = Field(default_factory=list)
    missing_metrics: list[str] = Field(default_factory=list)
    # True when the run changed >1 variable (fault_under_load). The builder
    # REFUSES to emit causal sentences when this is True unless a controlled
    # comparison exists.
    confounded: bool = False

    # --- action ---
    recommendations: list[Recommendation] = Field(default_factory=list)
    # Deterministic fix prompt (Markdown) generated from THIS report only.
    # Stored, not regenerated on fetch, so the artifact a user copies today
    # is byte-identical tomorrow.
    fix_prompt: str | None = None
    # Deterministic 0–100 score (P2). OptionalMetric because when scoring is
    # disabled the UI shows "score disabled", not a fake 0.
    score: OptionalMetric | None = None

    # --- AI (P2, optional) ---
    # Always rendered in a box labeled "AI-generated summary. Verify against
    # the measurements above." Never merged into deterministic text.
    ai_summary: str | None = None


class Comparison(BaseModel):
    """Before/after pair for the re-test flow. Produced by
    core/analysis/compare.py and GET /api/reports/compare?a=&b=."""

    before: Report
    after: Report
    # True when either config's CPU/memory limits or load shape differ — the
    # UI shows a fairness warning: "configs differ, improvement may not be
    # architectural". WHY: the pitch claims "same hardware, only the code
    # changed"; the tool must police that claim itself.
    fairness_warning: str | None = None
    # Per-metric deltas (after minus before), e.g. {"p95_ms": -180.0}.
    # Negative = improvement for latency/error metrics.
    deltas: dict[str, float | None] = Field(default_factory=dict)
    # Convenience booleans the UI badges directly.
    slo_before_passed: bool | None = None
    slo_after_passed: bool | None = None
    recovered_before: bool | None = None
    recovered_after: bool | None = None
