"""Codex runtime through the Codex App Server (`codex app-server`, JSON-RPC over stdio, one JSON per line).

Method and field names follow the schema generated by the installed CLI
(`codex app-server generate-json-schema --out schemas/codex`, checked against codex-cli 0.146.0):

  -> initialize {clientInfo}         <- result
  -> initialized (notification)
  -> thread/start | thread/resume    <- {thread: {id}, model, sandbox, approvalPolicy}
  -> turn/start {threadId, input}    <- {turn: {id, status}}
  <- item/started, item/completed, item/agentMessage/delta, item/commandExecution/outputDelta,
     thread/tokenUsage/updated, turn/plan/updated, error, turn/completed {turn: {status, error}}
  <- server requests: item/commandExecution/requestApproval, item/fileChange/requestApproval, ...
  -> turn/interrupt {threadId, turnId} to cancel

One app-server process per invocation: simple isolation and guaranteed cleanup. Reasoning items
are not stored. stdout carries only protocol messages; stderr goes to the log.
"""

import asyncio
import contextlib
import json
import logging
import os
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from app.config import settings
from app.runtime import workspace
from app.runtime.base import AgentRuntime, EventSink, RuntimeError_
from app.runtime.models import ProviderHealth, RuntimeEvent, RuntimeRequest, RuntimeResult

log = logging.getLogger("tower.runtime.codex")
CLIENT_INFO = {"name": "agent-control-tower", "title": "Agent Control Tower", "version": "0.1.0"}
TURN_STATUS = {"completed": "completed", "interrupted": "cancelled", "failed": "failed"}


class RpcError(RuntimeError_):
    def __init__(self, method: str, error: dict):
        super().__init__(f"{method}: {error.get('message', error)}")
        self.error = error


class JsonRpcConnection:
    """A JSON-RPC 2.0 peer over a subprocess's stdin/stdout (JSON lines)."""

    def __init__(self, argv: list[str], cwd: str | None = None, env: dict | None = None, on_request=None):
        self.argv, self.cwd, self.env = argv, cwd, env
        self.on_request = on_request              # async (method, params) -> result dict, or raises
        self.notifications: asyncio.Queue = asyncio.Queue()
        self.proc: asyncio.subprocess.Process | None = None
        self.malformed = 0
        self._pending: dict[int, asyncio.Future] = {}
        self._next_id = 0
        self._tasks: list[asyncio.Task] = []
        self._write_lock = asyncio.Lock()

    async def start(self) -> None:
        self.proc = await asyncio.create_subprocess_exec(
            *self.argv, cwd=self.cwd, env=self.env, limit=16 * 1024 * 1024,
            stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
        )
        self._tasks = [asyncio.create_task(self._read_stdout()), asyncio.create_task(self._drain_stderr())]

    async def _send(self, msg: dict) -> None:
        if self.proc is None or self.proc.stdin is None or self.proc.stdin.is_closing():
            raise RuntimeError_("app-server is not running")
        async with self._write_lock:
            try:
                self.proc.stdin.write((json.dumps(msg) + "\n").encode())
                await self.proc.stdin.drain()
            except (BrokenPipeError, ConnectionResetError) as exc:
                raise RuntimeError_(f"app-server pipe closed: {exc!r}") from exc

    async def request(self, method: str, params: dict | None = None, timeout: float = 60) -> Any:
        self._next_id += 1
        rid = self._next_id
        fut = asyncio.get_running_loop().create_future()
        self._pending[rid] = fut
        await self._send({"jsonrpc": "2.0", "id": rid, "method": method, "params": params or {}})
        try:
            msg = await asyncio.wait_for(fut, timeout)
        finally:
            self._pending.pop(rid, None)
        if "error" in msg:
            raise RpcError(method, msg["error"])
        return msg.get("result")

    async def notify(self, method: str, params: dict | None = None) -> None:
        msg = {"jsonrpc": "2.0", "method": method}
        if params is not None:
            msg["params"] = params
        await self._send(msg)

    async def answer(self, msg: dict) -> None:
        try:
            if self.on_request is None:
                raise LookupError("no handler")
            result = await self.on_request(msg["method"], msg.get("params") or {})
            await self._send({"jsonrpc": "2.0", "id": msg["id"], "result": result})
        except LookupError as exc:
            await self._send({"jsonrpc": "2.0", "id": msg["id"],
                              "error": {"code": -32601, "message": f"not supported by Control Tower: {exc}"}})
        except RuntimeError_:
            pass

    async def _read_stdout(self) -> None:
        assert self.proc and self.proc.stdout
        try:
            while line := await self.proc.stdout.readline():
                try:
                    msg = json.loads(line)
                except json.JSONDecodeError:
                    self.malformed += 1
                    log.warning("ignored malformed line from app-server: %r", line[:200])
                    continue
                if not isinstance(msg, dict):
                    self.malformed += 1
                    continue
                if "method" in msg:
                    # Notifications and server->client requests share one queue, so the consumer
                    # sees them in the order the server sent them (requests are answered via answer()).
                    await self.notifications.put(msg)
                elif "id" in msg and (fut := self._pending.get(msg["id"])) and not fut.done():
                    fut.set_result(msg)
        finally:
            for fut in self._pending.values():
                if not fut.done():
                    fut.set_exception(RuntimeError_("app-server exited"))
            await self.notifications.put(None)               # end-of-stream marker

    async def _drain_stderr(self) -> None:
        assert self.proc and self.proc.stderr
        while line := await self.proc.stderr.readline():
            log.debug("codex stderr: %s", line.decode(errors="replace").rstrip()[:500])

    async def close(self) -> None:
        if self.proc is None:
            return
        with contextlib.suppress(Exception):
            if self.proc.stdin and not self.proc.stdin.is_closing():
                self.proc.stdin.close()
        try:
            await asyncio.wait_for(self.proc.wait(), 3)
        except asyncio.TimeoutError:
            with contextlib.suppress(ProcessLookupError):
                self.proc.terminate()
            try:
                await asyncio.wait_for(self.proc.wait(), 3)
            except asyncio.TimeoutError:
                with contextlib.suppress(ProcessLookupError):
                    self.proc.kill()
                await self.proc.wait()
        for t in self._tasks:
            t.cancel()
        await asyncio.gather(*self._tasks, return_exceptions=True)


def codex_argv() -> list[str]:
    exe = shutil.which(settings.CODEX_BIN) or settings.CODEX_BIN
    if os.name == "nt" and exe.lower().endswith((".cmd", ".bat")):
        return ["cmd.exe", "/c", exe, "app-server"]   # fixed args only; the prompt goes over stdin
    return [exe, "app-server"]


@dataclass
class _Turn:
    conn: JsonRpcConnection
    thread_id: str | None = None
    turn_id: str | None = None
    cancel_requested: bool = False
    items: dict[str, dict] = field(default_factory=dict)


class CodexRuntime(AgentRuntime):
    name = "codex_app_server"
    provider = "codex"

    def __init__(self, argv: list[str] | None = None):
        self._argv = argv                       # tests pass a protocol-accurate fake server here
        self._active: dict[str, _Turn] = {}

    def _connection(self, request: RuntimeRequest | None, emit: EventSink | None) -> JsonRpcConnection:
        env = {**os.environ}
        if request:
            env.update(TOWER_INVOCATION_ID=str(request.invocation_id), TOWER_RUN_ID=request.run_id)
        return JsonRpcConnection(self._argv or codex_argv(), cwd=request.route.workspace_path if request else None,
                                 env=env, on_request=self._approval_handler(request, emit) if request else None)

    def _approval_handler(self, request: RuntimeRequest, emit: EventSink):
        """Codex asks before anything outside its sandbox. Policy: file changes inside the workspace are
        accepted when the agent may write; command escalations are declined (they'd leave the sandbox)."""
        ws = Path(request.route.workspace_path)

        async def handle(method: str, params: dict) -> dict:
            if method == "item/commandExecution/requestApproval":
                await emit(RuntimeEvent(event_type="approval.requested", why=params.get("reason"),
                                        payload={"kind": "command", "item_id": params.get("itemId"),
                                                 "command": params.get("command"), "cwd": params.get("cwd")}))
                decision = "decline"
            elif method == "item/fileChange/requestApproval":
                root = params.get("grantRoot")
                ok = request.route.permissions.get("write") and (root is None or workspace.contains(ws, root))
                await emit(RuntimeEvent(event_type="approval.requested", why=params.get("reason"),
                                        payload={"kind": "file_change", "item_id": params.get("itemId"),
                                                 "grant_root": root}))
                decision = "accept" if ok else "decline"
            else:
                raise LookupError(method)
            await emit(RuntimeEvent(event_type="approval.decided", payload={
                "item_id": params.get("itemId"), "decision": decision, "decided_by": "control-tower-policy"}))
            return {"decision": decision}

        return handle

    async def invoke(self, request: RuntimeRequest, emit: EventSink) -> RuntimeResult:
        route = request.route
        conn = self._connection(request, emit)
        turn = _Turn(conn=conn)
        key = str(request.invocation_id)
        self._active[key] = turn
        state: dict[str, Any] = {"last_text": None, "final": None, "usage": None, "errors": []}
        try:
            try:
                await conn.start()
            except OSError as exc:
                raise RuntimeError_(f"could not start codex app-server: {exc}") from exc
            await conn.request("initialize", {"clientInfo": CLIENT_INFO}, timeout=30)
            await conn.notify("initialized")

            thread_params = {"cwd": route.workspace_path, "sandbox": route.sandbox,
                             "approvalPolicy": settings.CODEX_APPROVAL_POLICY,
                             "developerInstructions": route.system_prompt}
            if route.model:
                thread_params["model"] = route.model
            if request.resume_provider_session_id:
                res = await conn.request("thread/resume", {"threadId": request.resume_provider_session_id,
                                                           **thread_params})
            else:
                res = await conn.request("thread/start", thread_params)
            turn.thread_id = res["thread"]["id"]
            await emit(RuntimeEvent(event_type="session.started", dedupe_key=f"thread:{turn.thread_id}", payload={
                "thread_id": turn.thread_id, "model": res.get("model"), "model_provider": res.get("modelProvider"),
                "sandbox": res.get("sandbox"), "approval_policy": res.get("approvalPolicy"),
                "resumed": bool(request.resume_provider_session_id)}))

            started = await conn.request("turn/start", {
                "threadId": turn.thread_id, "input": [{"type": "text", "text": request.prompt, "text_elements": []}]})
            turn.turn_id = started["turn"]["id"]
            if turn.cancel_requested:             # cancel arrived while the turn was starting
                await self._interrupt(turn)

            status, error = await self._pump(turn, state, emit)
        except (RuntimeError_, asyncio.TimeoutError, KeyError, TypeError) as exc:
            await emit(RuntimeEvent(event_type="execution.error",
                                    payload={"message": str(exc) or type(exc).__name__, "error_type": type(exc).__name__}))
            return RuntimeResult(status="cancelled" if turn.cancel_requested else "failed",
                                 error_message=f"{type(exc).__name__}: {exc}", provider_session_id=turn.thread_id,
                                 provider_thread_id=turn.thread_id, provider_turn_id=turn.turn_id,
                                 final_response=state["final"])
        finally:
            self._active.pop(key, None)
            await conn.close()

        total = (state["usage"] or {}).get("total") or {}
        return RuntimeResult(
            status=status, final_response=state["final"], error_message=error,
            provider_session_id=turn.thread_id, provider_thread_id=turn.thread_id, provider_turn_id=turn.turn_id,
            input_tokens=total.get("inputTokens"), output_tokens=total.get("outputTokens"), usage=state["usage"],
            metadata={"malformed_lines": conn.malformed},
        )

    async def _pump(self, turn: _Turn, state: dict, emit: EventSink) -> tuple[str, str | None]:
        """Read notifications until this turn completes. Returns (status, error message)."""
        while True:
            msg = await turn.conn.notifications.get()
            if msg is None:
                return ("cancelled" if turn.cancel_requested else "failed"), "codex app-server exited before the turn completed"
            method, p = msg.get("method"), msg.get("params") or {}
            if "id" in msg:                          # server -> client request (approvals), answered in order
                await turn.conn.answer(msg)
                continue
            if p.get("turnId") not in (None, turn.turn_id) or p.get("threadId") not in (None, turn.thread_id):
                continue
            if method == "item/agentMessage/delta":
                await emit(RuntimeEvent(event_type="message.delta", payload={"item_id": p.get("itemId"), "text": p.get("delta", "")}))
            elif method == "item/commandExecution/outputDelta":
                await emit(RuntimeEvent(event_type="command.output", payload={"item_id": p.get("itemId"), "text": p.get("delta", "")}))
            elif method == "item/started":
                await self._item_started(p.get("item") or {}, state, emit)
            elif method == "item/completed":
                await self._item_completed(p.get("item") or {}, state, emit)
            elif method == "turn/plan/updated":
                await emit(RuntimeEvent(event_type="plan.updated", payload={k: v for k, v in p.items() if k not in ("threadId", "turnId")}))
            elif method == "thread/tokenUsage/updated":
                state["usage"] = p.get("tokenUsage")
                await emit(RuntimeEvent(event_type="usage.updated", payload={"usage": p.get("tokenUsage")}))
            elif method == "error":
                err = p.get("error") or {}
                await emit(RuntimeEvent(event_type="execution.error", payload={
                    "message": err.get("message"), "details": err.get("additionalDetails"),
                    "will_retry": p.get("willRetry")}))
            elif method == "turn/completed":
                t = p.get("turn") or {}
                if t.get("id") != turn.turn_id:
                    continue
                status = TURN_STATUS.get(t.get("status"), "failed")
                if turn.cancel_requested and status != "completed":
                    status = "cancelled"
                return status, (t.get("error") or {}).get("message")

    async def _item_started(self, item: dict, state: dict, emit: EventSink) -> None:
        kind, iid = item.get("type"), item.get("id")
        # The only public "why" Codex exposes for an action is the visible message it wrote before it.
        why = state["last_text"][:300] if state["last_text"] else None
        source = {"why_source": "preceding_agent_message"} if why else {}
        if kind == "commandExecution":
            await emit(RuntimeEvent(event_type="command.started", why=why, dedupe_key=f"{iid}:start", payload={
                "item_id": iid, "command": item.get("command"), "cwd": item.get("cwd"),
                "actions": item.get("commandActions"), **source}))
        elif kind in ("mcpToolCall", "dynamicToolCall", "webSearch", "fileChange"):
            payload = {"item_id": iid, "tool": item.get("tool") or kind, "server": item.get("server"),
                       "input": item.get("arguments") if "arguments" in item else item.get("query"), **source}
            if kind == "fileChange":
                payload["paths"] = [c.get("path") for c in item.get("changes") or []]
            await emit(RuntimeEvent(event_type="tool.started", why=why, dedupe_key=f"{iid}:start", payload=payload))

    async def _item_completed(self, item: dict, state: dict, emit: EventSink) -> None:
        kind, iid = item.get("type"), item.get("id")
        if kind == "agentMessage":
            state["last_text"] = state["final"] = item.get("text")
            await emit(RuntimeEvent(event_type="message.completed", dedupe_key=f"{iid}:done",
                                    payload={"item_id": iid, "text": item.get("text"), "phase": item.get("phase")}))
        elif kind == "commandExecution":
            await emit(RuntimeEvent(event_type="command.completed", dedupe_key=f"{iid}:done", payload={
                "item_id": iid, "command": item.get("command"), "status": item.get("status"),
                "exit_code": item.get("exitCode"), "output": item.get("aggregatedOutput"),
                "duration_ms": item.get("durationMs")}))
        elif kind == "fileChange":
            for i, change in enumerate(item.get("changes") or []):
                await emit(RuntimeEvent(event_type="file.changed", dedupe_key=f"{iid}:file:{i}", payload={
                    "item_id": iid, "path": change.get("path"), "kind": (change.get("kind") or {}).get("type"),
                    "diff": change.get("diff"), "status": item.get("status")}))
            await emit(RuntimeEvent(event_type="tool.completed", dedupe_key=f"{iid}:done",
                                    payload={"item_id": iid, "tool": "fileChange", "status": item.get("status")}))
        elif kind in ("mcpToolCall", "dynamicToolCall", "webSearch"):
            await emit(RuntimeEvent(event_type="tool.completed", dedupe_key=f"{iid}:done", payload={
                "item_id": iid, "tool": item.get("tool") or kind, "status": item.get("status"),
                "result": item.get("result") or item.get("contentItems") or item.get("results"),
                "error": item.get("error"), "success": item.get("success")}))
        elif kind == "plan":
            await emit(RuntimeEvent(event_type="plan.updated", dedupe_key=f"{iid}:done", payload={"item_id": iid, "text": item.get("text")}))
        # reasoning items are not stored; userMessage echoes the prompt we already recorded.

    async def _interrupt(self, turn: _Turn) -> None:
        if turn.thread_id and turn.turn_id:
            with contextlib.suppress(RuntimeError_, asyncio.TimeoutError):
                await turn.conn.request("turn/interrupt", {"threadId": turn.thread_id, "turnId": turn.turn_id}, timeout=10)

    async def cancel(self, invocation_id: str) -> bool:
        turn = self._active.get(invocation_id)
        if turn is None:
            return False
        turn.cancel_requested = True
        await self._interrupt(turn)
        return True

    async def health(self) -> ProviderHealth:
        enabled = settings.CODEX_RUNTIME_ENABLED
        argv = self._argv or codex_argv()
        if not self._argv and not shutil.which(settings.CODEX_BIN):
            return ProviderHealth(provider="codex", enabled=enabled, available=False,
                                  detail=f"{settings.CODEX_BIN!r} not found on PATH")
        conn = JsonRpcConnection(argv)
        try:
            await conn.start()
            init = await conn.request("initialize", {"clientInfo": CLIENT_INFO}, timeout=20)
            await conn.notify("initialized")
            acct = await conn.request("account/read", {}, timeout=20)
        except (OSError, RuntimeError_, asyncio.TimeoutError) as exc:
            return ProviderHealth(provider="codex", enabled=enabled, available=False,
                                  detail=f"app-server handshake failed: {exc!r}")
        finally:
            await conn.close()
        ua = (init or {}).get("userAgent", "")
        version = ua.split(" ")[0].split("/")[-1] if "/" in ua else None
        account = (acct or {}).get("account")
        # Only the account type and plan are reported; never the email.
        auth = f"{account['type']}" + (f" ({account.get('planType')})" if account.get("planType") else "") if account else None
        logged_in = account is not None or not (acct or {}).get("requiresOpenaiAuth", True)
        return ProviderHealth(provider="codex", enabled=enabled, available=logged_in, version=version,
                              auth_mode=auth or "not logged in",
                              detail="app-server handshake ok" + ("" if logged_in else "; run `codex login`"))
