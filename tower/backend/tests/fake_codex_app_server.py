"""A stand-in for `codex app-server` used only by tests: speaks the same JSON-lines JSON-RPC protocol
(method and field names from the schema generated by codex-cli 0.146.0) and scripts one turn.

FAKE_CODEX_MODE: ok (default) | fail | hang (waits for turn/interrupt) | garbage (malformed line first)
FAKE_CODEX_LOG:  file that receives every message the client sent, one JSON per line, then "EOF".
"""

import json
import os
import sys

MODE = os.environ.get("FAKE_CODEX_MODE", "ok")
LOG = os.environ.get("FAKE_CODEX_LOG")
THREAD, TURN = "thr_test_1", "turn_test_1"
_next_server_id = 1000


def log(entry):
    if LOG:
        with open(LOG, "a", encoding="utf-8") as f:
            f.write((entry if isinstance(entry, str) else json.dumps(entry)) + "\n")


def send(msg):
    sys.stdout.write(json.dumps(msg) + "\n")
    sys.stdout.flush()


def note(method, **params):
    send({"method": method, "params": {"threadId": THREAD, "turnId": TURN, **params}})


def read():
    line = sys.stdin.readline()
    if not line:
        log("EOF")
        sys.exit(0)
    msg = json.loads(line)
    log(msg)
    return msg


def ask(method, params):
    """Server -> client request; returns the client's result."""
    global _next_server_id
    _next_server_id += 1
    send({"id": _next_server_id, "method": method, "params": params})
    while True:
        msg = read()
        if msg.get("id") == _next_server_id and "method" not in msg:
            return msg.get("result")


def run_turn(prompt):
    note("turn/started", turn={"id": TURN, "items": [], "status": "inProgress"})
    note("item/started", item={"type": "userMessage", "id": "u1", "content": [{"type": "text", "text": prompt}]},
         startedAtMs=1)
    if MODE == "hang":
        while True:
            msg = read()
            if msg.get("method") == "turn/interrupt":
                send({"id": msg["id"], "result": {}})
                note("turn/completed", turn={"id": TURN, "items": [], "status": "interrupted"})
                return
    note("item/completed", item={"type": "agentMessage", "id": "m1", "text": "I'll inspect auth.py for the login flow."},
         completedAtMs=2)
    note("item/started", item={"type": "commandExecution", "id": "c1", "command": "cat auth.py", "cwd": ".",
                                "commandActions": [], "status": "inProgress"}, startedAtMs=3)
    note("item/commandExecution/outputDelta", itemId="c1", delta="import hashlib\n")
    note("item/completed", item={"type": "commandExecution", "id": "c1", "command": "cat auth.py", "cwd": ".",
                                  "commandActions": [], "status": "completed", "exitCode": 0,
                                  "aggregatedOutput": "import hashlib\nAPI_KEY=sk-ant-abcdefghijklmnopqrstuvwxyz\n",
                                  "durationMs": 12}, completedAtMs=4)
    decision = ask("item/fileChange/requestApproval",
                   {"threadId": THREAD, "turnId": TURN, "itemId": "f1", "startedAtMs": 5,
                    "reason": "Write the review notes next to the code"})
    note("item/completed", item={"type": "fileChange", "id": "f1", "status": "completed" if decision.get("decision") == "accept" else "declined",
                                  "changes": [{"path": "REVIEW.md", "kind": {"type": "add"}, "diff": "+ use bcrypt"}]},
         completedAtMs=6)
    if MODE == "fail":
        note("error", error={"message": "model overloaded"}, willRetry=False)
        note("turn/completed", turn={"id": TURN, "items": [], "status": "failed", "error": {"message": "model overloaded"}})
        return
    note("item/agentMessage/delta", itemId="m2", delta="Found 3 ")
    note("item/agentMessage/delta", itemId="m2", delta="problems.")
    note("item/completed", item={"type": "agentMessage", "id": "m2", "text": "Found 3 problems."}, completedAtMs=7)
    note("thread/tokenUsage/updated", tokenUsage={
        "last": {"inputTokens": 50, "outputTokens": 10, "cachedInputTokens": 0, "reasoningOutputTokens": 0, "totalTokens": 60},
        "total": {"inputTokens": 120, "outputTokens": 30, "cachedInputTokens": 0, "reasoningOutputTokens": 0, "totalTokens": 150}})
    note("turn/completed", turn={"id": TURN, "items": [], "status": "completed"})


def main():
    if MODE == "garbage":
        sys.stdout.write("this is not json\n")
        sys.stdout.flush()
    while True:
        msg = read()
        method, rid = msg.get("method"), msg.get("id")
        if method == "initialize":
            send({"id": rid, "result": {"userAgent": "agent-control-tower/0.146.0 (test)", "codexHome": "/tmp"}})
        elif method == "initialized":
            continue
        elif method == "account/login/start":
            send({"id": rid, "result": {"type": "chatgpt", "authUrl": "https://auth.openai.com/oauth/authorize?test=1",
                                        "loginId": "login-1"}})
            send({"method": "account/login/completed", "params": {"loginId": "login-1", "success": True, "error": None}})
        elif method == "account/read":
            send({"id": rid, "result": {"account": {"type": "chatgpt", "email": "someone@example.com", "planType": "plus"},
                                        "requiresOpenaiAuth": True}})
        elif method in ("thread/start", "thread/resume"):
            global THREAD
            THREAD = msg["params"].get("threadId", THREAD)
            send({"id": rid, "result": {"thread": {"id": THREAD}, "model": msg["params"].get("model") or "gpt-test",
                                        "modelProvider": "openai", "sandbox": {"type": msg["params"].get("sandbox")},
                                        "approvalPolicy": msg["params"].get("approvalPolicy"), "cwd": "."}})
        elif method == "turn/start":
            send({"id": rid, "result": {"turn": {"id": TURN, "items": [], "status": "inProgress"}}})
            run_turn(msg["params"]["input"][0]["text"])
        elif rid is not None:
            send({"id": rid, "error": {"code": -32601, "message": f"unknown method {method}"}})


if __name__ == "__main__":
    main()
